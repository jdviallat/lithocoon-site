(function(){
  var LANGS=[["fr","Français"],["en","English"],["de","Deutsch"],["it","Italiano"],["pt","Português"],["es","Español"],["sv","Svenska"],["no","Norsk"],["fi","Suomi"]];
  var DEFAULT="fr";
  function get(){try{return localStorage.getItem("litho_lang");}catch(e){return null;}}
  function set(v){try{localStorage.setItem("litho_lang",v);}catch(e){}}
  var originals=[];
  function cache(){
    document.querySelectorAll("[data-i18n]").forEach(function(el){originals.push([el,"text",el.getAttribute("data-i18n"),el.textContent]);});
    document.querySelectorAll("[data-i18n-html]").forEach(function(el){originals.push([el,"html",el.getAttribute("data-i18n-html"),el.innerHTML]);});
  }
  function apply(lang){
    var dict=(window.I18N&&window.I18N[lang])||null;
    document.documentElement.lang=lang;
    originals.forEach(function(o){
      var el=o[0],type=o[1],key=o[2],orig=o[3];
      var val=(dict&&dict[key]!=null)?dict[key]:orig;
      if(type==="html"){el.innerHTML=val;}else{el.textContent=val;}
    });
    var sel=document.getElementById("langSel");if(sel){sel.value=lang;}
    set(lang);
  }
  function initial(){
    var s=get();if(s){return s;}
    var n=(navigator.language||"").slice(0,2).toLowerCase();
    for(var i=0;i<LANGS.length;i++){if(LANGS[i][0]===n){return n;}}
    return DEFAULT;
  }
  function build(){
    var sel=document.getElementById("langSel");
    if(sel){
      sel.innerHTML=LANGS.map(function(l){return '<option value="'+l[0]+'">'+l[1]+'</option>';}).join("");
      sel.addEventListener("change",function(){apply(sel.value);});
    }
    cache();
    apply(initial());
  }
  if(document.readyState==="loading"){document.addEventListener("DOMContentLoaded",build);}else{build();}
})();
